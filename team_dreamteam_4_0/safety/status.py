"""Определение рабочего статуса мобильной платформы.

Модуль реализует строгую логику сопоставления состояний платформы
в соответствии с критерием Т4 честности статусов симулятора.
"""


def determine_status(
    v_odom: float,
    w_odom: float = 0.0,
    is_arrived: bool = False,
    is_lost: bool = False,
    is_stopped: bool = False,
    is_slowed: bool = False,
    is_estop: bool = False,
    allow_slowed: bool = False,
) -> str:
    """Определить рабочий статус мобильной платформы по критерию Т4.

    Ключевые требования критерия Т4 и правила арбитража статусов:
    - привязка статуса движения к фактической одометрии: симулятор проверяет
      реальное физическое движение колес по порогам скорости линейной 0.05 м/с
      или угловой 0.10 рад/с; если платформа физически катится по инерции
      при команде торможения, выставление любого не связанного с движением
      статуса наказывается штрафом status_mismatch величиной -2 балла за каждый
      такт расхождения;
    - статус moving выставляется всегда при |v_odom| >= 0.05 м/с или
      |w_odom| >= 0.10 рад/с независимо от внутренних намерений планировщика;
    - статус lost разрешен исключительно при полной физической остановке платформы:
      если локализация потеряна на ходу, робот сначала гасит скорость,
      сохраняя статус движения, и только после падения скоростей ниже порогов
      переходит в статус lost;
    - приоритет прибытия: статус arrived выставляется безусловно при фиксации
      успешного позиционирования в точке разгрузки;
    - приоритет экстренной остановки: статус estop выставляется при срабатывании
      контура защиты от неминуемого столкновения;
    - статус waiting выставляется в неподвижном состоянии при ожидании освобождения
      траектории пешеходом или препятствием;
    - статус slowed выставляется только при явном разрешении флагом allow_slowed
      во время движения на сниженной скорости.

    Параметры:
      v_odom: измеренная линейная скорость по одометрии в м/с;
      w_odom: измеренная угловая скорость по одометрии в рад/с;
      is_arrived: признак успешного прибытия в целевую зону;
      is_lost: признак потери достоверной оценки координат;
      is_stopped: признак намеренной остановки перед препятствием;
      is_slowed: признак движения со сниженной скоростью;
      is_estop: признак срабатывания экстренного торможения;
      allow_slowed: флаг разрешения отдельного статуса замедления.

    Возвращает:
      строковый идентификатор статуса платформы.
    """
    if is_arrived:
        return "arrived"
    if is_estop:
        return "estop"

    # Критерий Т4: исключение штрафа status_mismatch по порогам физической одометрии
    if abs(v_odom) >= 0.05 or abs(w_odom) >= 0.10:
        if allow_slowed and is_slowed:
            return "slowed"
        return "moving"

    # Стационарное состояние платформы при скорости ниже порога 0.05 м/с
    # Статус lost допустим только после полной остановки во избежание штрафа
    if is_lost:
        return "lost"
    if is_stopped:
        return "waiting"
    if is_slowed and allow_slowed:
        return "slowed"

    return "waiting"
