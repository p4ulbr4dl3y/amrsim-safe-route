"""Модуль стробирования точности ГНСС и комплексирования измерений.

Включает:
- стробирование невязки по критерию Т4 (порог 1.5 м, адаптация к качеству сигнала);
- учет фактора снижения точности и затенения ГНСС;
- взвешенную коррекцию координат и дисперсий без прямого копирования измерений;
- детектор устойчивого расхождения и восстановление при сдвиге вдоль стен.

Соответствует требованиям Т3 и Т5 (только стандартная библиотека и библиотека вычислений).
"""

import math
from typing import List, Tuple

import numpy as np


class GNSSFilter:
    """Стробирование измерений ГНСС и комплексирование с фильтром состояния.

    Реализует требования критерия Т4 по честности оценки позы:
    - запрет прямого копирования координат ГНСС в оценку позы платформы;
    - физическая фильтрация выбросов через стробирование инновации (невязки);
    - ограничение коэффициента усиления фильтра для исключения скачков позы;
    - отбрасывание недостоверных измерений при ухудшении геометрии спутников.
    """

    def __init__(self) -> None:
        self.rejections: List[Tuple[float, float]] = []
        self.last_accepted: bool = False
        self.fix_ticks: int = 10**9

    def update(
        self,
        x: float,
        y: float,
        var_along: float,
        var_cross: float,
        gnss_x: float,
        gnss_y: float,
        gnss_valid: bool,
        gnss_hdop: float,
        in_shadow: bool = False,
        scan_inliers: int = 0,
        fog_active: bool = False,
    ) -> Tuple[bool, float, float, float, float, bool]:
        """Обновить состояние по измерению ГНСС со стробированием невязки.

        Физика стробирования невязки и комплексирования по критерию Т4:
        - отсечение по геометрическому фактору: измерения отбрасываются при
          факторе снижения точности больше 2.0, в зонах радиотени или при флаге
          недостоверности данных;
        - стробирование невязки: допустимое расхождение между измерением ГНСС и
          текущей оценкой позы ограничено стробом 1.5 м (при отсутствии
          подтверждения по лидарному скану строб ужесточается до 0.6 м);
        - взвешенное подмешивание: прямое копирование координат ГНСС в позу строго
          запрещено; коррекция выполняется с весовым коэффициентом не более 0.15,
          что предотвращает дискретные скачки оценки и обеспечивает гладкость
          траектории;
        - адаптация к условиям наблюдения: при факторе снижения точности больше 1.4
          коэффициент усиления дополнительно снижается в два раза, а при слабом
          подтверждении сканом стен - более чем в три раза.

        Параметры:
          x: текущая координата x платформы;
          y: текущая координата y платформы;
          var_along: дисперсия позы вдоль направления движения;
          var_cross: дисперсия позы поперек направления движения;
          gnss_x: координата x по измерению приемника ГНСС;
          gnss_y: координата y по измерению приемника ГНСС;
          gnss_valid: флаг валидности решения навигационного приемника;
          gnss_hdop: геометрический фактор снижения точности в горизонтальной плоскости;
          in_shadow: признак нахождения платформы в зоне радиотени;
          scan_inliers: количество точек лидарного скана, сопоставленных со стенами;
          fog_active: флаг активности детектора тумана.

        Возвращает:
          кортеж признака принятия измерения, обновленных координат x и y,
          обновленных дисперсий вдоль и поперек пути, а также флага сброса
          неподтвержденного расстояния.
        """
        self.last_accepted = False

        # Отсечение измерений при радиотени, невалидном статусе или высоком факторе снижения точности
        if in_shadow or not gnss_valid or gnss_hdop > 2.0:
            self.rejections.clear()
            self.fix_ticks += 1
            return False, x, y, var_along, var_cross, False

        dx = gnss_x - x
        dy = gnss_y - y
        dist = math.hypot(dx, dy)

        # Стробирование невязки ГНСС: базовый допуск составляет 1.5 м
        if dist < 1.5:
            scan_ok = (scan_inliers >= 30) or fog_active
            if not scan_ok and dist > 0.6:
                # Карта не подтверждает позу: удержание до восстановления совпадения
                self.fix_ticks += 1
                self.rejections.append((dx, dy))
                return False, x, y, var_along, var_cross, False

            self.rejections.clear()
            # Модель шума измерения ГНСС с масштабированием по геометрическому фактору точности
            r_var = (0.3 * max(1.0, gnss_hdop)) ** 2
            k_x = var_along / (var_along + r_var)
            k_y = var_cross / (var_cross + r_var)
            # Ограничение коэффициента подмешивания значением не более 0.15 (запрет прямого копирования)
            k = max(0.01, min(0.15, 0.5 * (k_x + k_y)))
            if gnss_hdop > 1.4:
                k *= 0.5
            if not scan_ok:
                k *= 0.3

            # Плавная коррекция позы без скачков
            new_x = x + k * dx
            new_y = y + k * dy
            new_var_along = max(0.04, var_along * (1.0 - k))
            new_var_cross = max(0.04, var_cross * (1.0 - k))

            self.last_accepted = True
            self.fix_ticks = 0
            return True, new_x, new_y, new_var_along, new_var_cross, True

        # Отклоненная невязка: проверка устойчивого согласия измерений
        self.fix_ticks += 1
        self.rejections.append((dx, dy))

        if len(self.rejections) >= 60:
            recent = np.array(self.rejections[-40:])
            shift_x = float(recent[:, 0].mean())
            shift_y = float(recent[:, 1].mean())
            shift = math.hypot(shift_x, shift_y)
            if recent.std(axis=0).max() < 0.5 and scan_inliers >= 60 and 1.5 < shift < 3.0:
                # Фильтр сдрейфовал вдоль гладкой стены, данные ГНСС стабильны
                new_x = x + shift_x
                new_y = y + shift_y
                new_var_along = 0.5**2
                new_var_cross = 0.5**2
                self.rejections.clear()
                self.last_accepted = True
                return True, new_x, new_y, new_var_along, new_var_cross, False
            if len(self.rejections) > 80:
                self.rejections.pop(0)

        return False, x, y, var_along, var_cross, False
